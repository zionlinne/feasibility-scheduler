@dataclass
class _ArtifactSink:
    """验收时按文件独立交付到 workspace：临时文件 + 原子替换，并记录哈希/状态。"""

    workspace: Path
    written: list[str] = field(default_factory=list)
    manifest: list[str] = field(default_factory=list)
    delivery: dict[str, dict[str, Any]] = field(default_factory=dict)

    def register_manifest(self, paths: Sequence[str]) -> list[str]:
        """先登记文件清单（相对 workspace 的路径）。"""
        clean: list[str] = []
        for rel in paths:
            if not isinstance(rel, str) or not rel.strip():
                continue
            norm = rel.replace("\\", "/").strip()
            if not norm or norm in clean:
                continue
            clean.append(norm)
        self.manifest = list(clean)
        for path in clean:
            self.delivery.setdefault(
                path,
                {
                    "path": path,
                    "status": "registered",
                    "hash": None,
                    "bytes": 0,
                    "error": None,
                },
            )
        return list(clean)

    def _safe_target(self, rel: str) -> Path | None:
        if not isinstance(rel, str) or not rel.strip():
            return None
        target = (self.workspace / rel).resolve()
        root = self.workspace.resolve()
        try:
            target.relative_to(root)
        except ValueError:
            return None
        return target

    def deliver_file(self, rel: str, content: str) -> dict[str, Any]:
        """单文件独立交付：校验 → 写临时文件 → os.replace 原子替换 → 记哈希。"""
        norm = rel.replace("\\", "/").strip()
        record: dict[str, Any] = {
            "path": norm,
            "status": "failed",
            "hash": None,
            "bytes": 0,
            "error": None,
        }
        if not isinstance(content, str):
            record["error"] = "content_not_string"
            self.delivery[norm] = record
            return record
        target = self._safe_target(norm)
        if target is None:
            record["error"] = "path_escapes_workspace"
            self.delivery[norm] = record
            return record
        prior = self.delivery.get(norm)
        if prior is not None and prior.get("status") == "delivered":
            return dict(prior)
        data = content.encode("utf-8")
        digest = hashlib.sha256(data).hexdigest()
        target.parent.mkdir(parents=True, exist_ok=True)
        tmp_path: Path | None = None
        try:
            with tempfile.NamedTemporaryFile(
                mode="wb",
                delete=False,
                dir=str(target.parent),
                prefix=f".{target.name}.",
                suffix=".tmp",
            ) as tmp:
                tmp.write(data)
                tmp.flush()
                os.fsync(tmp.fileno())
                tmp_path = Path(tmp.name)
            os.replace(str(tmp_path), str(target))
            tmp_path = None
            record["status"] = "delivered"
            record["hash"] = f"sha256:{digest}"
            record["bytes"] = len(data)
            if norm not in self.written:
                self.written.append(norm)
        except OSError as exc:
            record["error"] = f"write_failed:{exc}"
            if tmp_path is not None and tmp_path.exists():
                try:
                    tmp_path.unlink()
                except OSError:
                    pass
        self.delivery[norm] = record
        return record

    def write_files(self, files: Mapping[str, Any]) -> list[str]:
        """兼容旧路径：把 files 映射拆成逐文件独立交付。"""
        written: list[str] = []
        for rel, content in files.items():
            if not isinstance(rel, str) or not isinstance(content, str):
                continue
            result = self.deliver_file(rel, content)
            if result.get("status") == "delivered":
                written.append(rel.replace("\\", "/"))
        return written

    def delivery_snapshot(self) -> dict[str, Any]:
        return {
            "manifest": list(self.manifest),
            "files": {k: dict(v) for k, v in self.delivery.items()},
        }


class PromptFromPayloadExecutor(ContractExecutionMixin, ArtifactMetadataExecutorMixin, Executor):
    """向后兼容扩展：若 payload 含 prompt_text 则用之，否则走内核默认 JSON dump。"""

    def _prompt(self, task_id: str) -> str:
        task = self._task_by_id[task_id]
        text = task.payload.get("prompt_text") if task.payload else None
        if isinstance(text, str) and text.strip():
            return text
        return super()._prompt(task_id)


class _PlaceholderClient:
    """适配层专用 Fake：按 task_id 返回占位 files，不触网、不改 FakeClient。"""

    def __init__(self, tasks: Sequence[Task], *, model: str = "fake-model-1") -> None:
        self.model = model
        self.provider = "fake-legacy-placeholder"
        self._by_id = {t.id: t for t in tasks}
        self._ledger: dict[str, RequestStatus] = {}
        self._responses: list[ApiResponse] = []
        self._serial = 0

    def call(self, request: ApiRequest) -> ApiResponse:
        if not isinstance(request, ApiRequest):
            raise RequestValidationError("request 必须是 ApiRequest")
        if request.idempotency_key in self._ledger:
            # 幂等重放：返回上次
            for resp in reversed(self._responses):
                if resp.idempotency_key == request.idempotency_key:
                    return resp
        task = self._by_id.get(request.task_id)
        owned = []
        if task is not None:
            raw = task.payload.get("owned_files") or []
            owned = [x for x in raw if isinstance(x, str)]
        files = {path: _PLACEHOLDER_STUB for path in owned}
        body_obj = {"ok": True, "files": files, "notes": "placeholder"}
        body = json.dumps(body_obj, ensure_ascii=False)
        self._serial += 1
        now = datetime(2026, 1, 1, tzinfo=timezone.utc)
        response = ApiResponse(
            request_id=f"legacy-fake-{self._serial:06d}",
            idempotency_key=request.idempotency_key,
            task_id=request.task_id,
            provider=self.provider,
            model=self.model,
            outcome=Outcome.SUCCESS,
            status_code=200,
            raw_body=body,
            parsed_body=body_obj,
            usage={"input_tokens": 1, "output_tokens": 1},
            error_type=None,
            retry_after_seconds=None,
            is_duplicate=False,
            duplicate_of=None,
            attempt=1,
            started_at=now,
            finished_at=now,
            input_artifact_hash=request.input_artifact_hash or "",
        )
        self._ledger[request.idempotency_key] = RequestStatus.SENT
        self._responses.append(response)
        return response

    async def acall(self, request: ApiRequest) -> ApiResponse:
        return self.call(request)

    def request_status(self, idempotency_key: str) -> RequestStatus:
        return self._ledger.get(idempotency_key, RequestStatus.NOT_SENT)

    def lookup_response(self, idempotency_key: str) -> ApiResponse | None:
        for resp in reversed(self._responses):
            if resp.idempotency_key == idempotency_key and not resp.is_duplicate:
                return resp
        return None


def make_placeholder_client(tasks: Sequence[Task], **kwargs: Any) -> SchedulerClient:
    return _PlaceholderClient(tasks, **kwargs)


def load_task_input(path: Path | str) -> dict[str, Any]:
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(data, dict) or "modules" not in data:
        raise ValueError("TASK_INPUT.json 必须是含 modules 的对象")
    if not isinstance(data["modules"], list) or not data["modules"]:
        raise ValueError("modules 不能为空")
    return data


def _module_prompt(
    *,
    task_md: str,
    module: Mapping[str, Any],
    sibling_files: Sequence[str],
) -> str:
    module_id = str(module.get("module_id", ""))
    title = str(module.get("title", ""))
    owned = [x for x in (module.get("owned_files") or []) if isinstance(x, str)]
    outputs = [x for x in (module.get("outputs") or []) if isinstance(x, str)]
    deps = module.get("deps") or []
    accept = module.get("accept_commands") or []

    files_schema = {path: "<完整源码字符串>" for path in owned}
    sibling_note = ""
    if sibling_files:
        sibling_note = (
            "\n已存在/将由其它模块产出的路径（只读参考，不要覆盖非本模块 owned_files）：\n"
            + "\n".join(f"- {p}" for p in sibling_files)
            + "\n"
        )

    # 多文件时优先「清单 + 单文件」交付，避免一次塞整模块大 JSON。
    if len(owned) <= 1:
        schema_hint = {
            "ok": True,
            "delivery": "files",
            "files": files_schema,
            "notes": "可选说明",
        }
        delivery_rules = (
            "- `ok` 必须为 true。\n"
            "- 单文件可用 `files`：键覆盖 owned_files，值为完整内容字符串。\n"
        )
    else:
        schema_hint = {
            "ok": True,
            "delivery": "file",
            "manifest": owned,
            "file": {"path": owned[0], "content": "<完整源码字符串>"},
            "notes": "多文件时优先每次只交付一个 file；也可用 files 批量但易触顶截断",
        }
        delivery_rules = (
            "- `ok` 必须为 true。\n"
            "- **不要**把整模块所有大文件一次性塞进唯一 `files` 大 JSON 作为唯一路径。\n"
            "- 推荐协议：\n"
            "  1) 先登记清单：`{\"ok\":true,\"delivery\":\"manifest\",\"manifest\":[...owned_files]}\n"
            "  2) 每文件独立交付：`{\"ok\":true,\"delivery\":\"file\",\"file\":{\"path\":\"...\",\"content\":\"...\"}}`\n"
            "  3) 兼容批量：`{\"ok\":true,\"delivery\":\"files\",\"files\":{...}}`（适配层仍逐文件校验/落盘）\n"
            "- 输出过长将被截断并标记 OUTPUT_TRUNCATED，而非普通代码错误。\n"
        )

    return (
        "你是资深 Node.js 工程师。请根据下列完整题目规格，实现指定模块，"
        "并**只**输出一个 JSON 对象（不要 markdown 围栏，不要其它说明文字）。\n\n"
        f"## 本模块\n- module_id: {module_id}\n- title: {title}\n"
        f"- deps: {json.dumps(deps, ensure_ascii=False)}\n"
        f"- owned_files: {json.dumps(owned, ensure_ascii=False)}\n"
        f"- outputs: {json.dumps(outputs, ensure_ascii=False)}\n"
        f"- accept_commands（参考）: {json.dumps(accept, ensure_ascii=False)}\n"
        f"{sibling_note}\n"
        "## 输出 JSON schema（示例）\n"
        + json.dumps(schema_hint, ensure_ascii=False, indent=2)
        + "\n\n规则：\n"
        + delivery_rules
        + "- 仅使用 Node.js 24 标准库；禁止第三方依赖。\n"
        "- 严格按题目行为实现，不要发明额外 API。\n"
        "- 若信息不足，仍须给出可 `node --check` 通过的最佳努力实现，并在 notes 说明假设。"
        "（仅对 .js/.mjs/.cjs；README.md 等非 JS 不要指望 node --check。）\n\n"
        "## 题目规格 TASK.md\n\n"
        + task_md.strip()
        + "\n"
    )


def build_legacy_tasks(
    task_input: Mapping[str, Any],
    *,
    task_md: str,
    module_ids: Iterable[str] | None = None,
) -> list[Task]:
    modules = list(task_input["modules"])
    references = task_input.get("reference_files", {})
    if not isinstance(references, dict) or any(not isinstance(k, str) or not isinstance(v, str) for k, v in references.items()):
        raise ValueError("reference_files must map relative artifact paths to text contents")
    wanted = set(module_ids) if module_ids is not None else None
    if wanted is not None:
        missing = wanted - {m.get("module_id") for m in modules}
        if missing:
            raise ValueError(f"未知 module_id: {sorted(missing)}")
        modules = [m for m in modules if m.get("module_id") in wanted]
        # 裁剪后依赖必须仍在所选集合内，否则去掉越界 deps
        selected = {m["module_id"] for m in modules}
        trimmed: list[dict[str, Any]] = []
        for m in modules:
            deps = [d for d in (m.get("deps") or []) if d in selected]
            copy = dict(m)
            copy["deps"] = deps
            trimmed.append(copy)
        modules = trimmed

    all_owned: list[str] = []
    for m in modules:
        all_owned.extend(x for x in (m.get("owned_files") or []) if isinstance(x, str))

    tasks: list[Task] = []
    for m in modules:
        mid = str(m["module_id"])
        owned = [x for x in (m.get("owned_files") or []) if isinstance(x, str)]
        deps = tuple(str(d) for d in (m.get("deps") or []))
        prompt = _module_prompt(
            task_md=task_md,
            module=m,
            sibling_files=[p for p in all_owned if p not in owned],
        )
        if references:
            prompt += "\nREAD-ONLY PROVIDED MATERIALS (do not overwrite)\n" + json.dumps(references, ensure_ascii=False)
        payload = {
            "module_id": mid,
            "title": m.get("title"),
            "owned_files": owned,
            "outputs": list(m.get("outputs") or []),
            "accept_commands": list(m.get("accept_commands") or []),
            "deps": list(deps),
            "estimated_tokens": m.get("estimated_tokens"),
            "prompt_text": prompt,
            "reference_files": references,
            "external_checker_names": list(task_input.get("external_checker_names", [])),
        }
        tasks.append(
            Task(
                id=mid,
                dependencies=deps,
                constraints=(),
                constraints_declared=True,
                output_contract=dict(DEFAULT_OUTPUT_CONTRACT),
                payload=payload,
            )
        )
    return tasks


def _is_node_checkable(path: str) -> bool:
    """按扩展名决定是否允许 node --check；非 JS 不得进入 node。"""
    suffix = Path(path.replace("\\", "/")).suffix.lower()
    return suffix in NODE_CHECK_SUFFIXES


def _extract_delivery_files(body: Mapping[str, Any]) -> tuple[dict[str, str], list[str], str]:
    """从响应体提取待交付文件映射。

    支持：
    - delivery=file + file={path,content}
    - delivery=manifest + manifest=[...]（无内容，仅登记）
    - delivery=files / 缺省 + files={...}（兼容旧批量路径，但仍逐文件处理）
    """
    errors: list[str] = []
    delivery = body.get("delivery")
    if delivery is None:
        mode = "files" if "files" in body else ("file" if "file" in body else "manifest")
    elif isinstance(delivery, str) and delivery.strip():
        mode = delivery.strip().lower()
    else:
        mode = "files"

    out: dict[str, str] = {}

    if mode == "manifest":
        return out, errors, "manifest"

    if mode == "file":
        item = body.get("file")
        if not isinstance(item, Mapping):
            errors.append("delivery=file 但 file 不是对象")
            return out, errors, "file"
        path = item.get("path")
        content = item.get("content")
        if not isinstance(path, str) or not path.strip():
            errors.append("file.path 无效")
        elif not isinstance(content, str):
            errors.append(f"file.content 非字符串: {path}")
        else:
            out[path.replace("\\", "/")] = content
        return out, errors, "file"

    # files / 其它：兼容旧整包 files
    files = body.get("files")
    if not isinstance(files, Mapping):
        errors.append("files 不是对象")
        return out, errors, "files"
    for path, content in files.items():
        if not isinstance(path, str) or not path.strip():
            errors.append("files 含无效键")
            continue
        if not isinstance(content, str):
            errors.append(f"文件 {path} 内容为空或非字符串")
            continue
        if not content.strip():
            errors.append(f"文件 {path} 内容为空或非字符串")
            continue
        out[path.replace("\\", "/")] = content
    return out, errors, "files"


def _looks_output_truncated(response: ApiResponse, body: Mapping[str, Any] | None) -> bool:
    """适配层侧截断判定：error_type / usage 触顶 / 正文声明。"""
    if getattr(response, "error_type", None) == "output_truncated":
        return True
    usage = response.usage or {}
    out_tokens = usage.get("output_tokens") if isinstance(usage, Mapping) else None
    if isinstance(out_tokens, int) and out_tokens >= OUTPUT_TOKEN_HARD_LIMIT:
        return True
    if isinstance(body, Mapping):
        note = body.get("notes") or body.get("error") or ""
        if isinstance(note, str) and "OUTPUT_TRUNCATED" in note:
            return True
    return False


def _write_raw_audit(
    sink: _ArtifactSink,
    task: Task,
    response: ApiResponse,
    body: Any,
    extra: Mapping[str, Any] | None = None,
) -> None:
    """验收路径上的 Raw 审计。失败返回前也要写，避免只在成功/部分交付时才有 Raw。"""
    raw_dir = sink.workspace / "_raw_responses"
    raw_dir.mkdir(parents=True, exist_ok=True)
    payload: dict[str, Any] = {
        "task_id": task.id,
        "request_id": response.request_id,
        "outcome": response.outcome.value,
        "error_type": getattr(response, "error_type", None),
        "usage": _to_plain(response.usage),
        "parsed_body": _to_plain(body) if isinstance(body, Mapping) else None,
        "raw_body": response.raw_body if isinstance(response.raw_body, str) else None,
        "delivery": sink.delivery_snapshot(),
    }
    if extra:
        payload.update(dict(extra))
    (raw_dir / f"{task.id}.json").write_text(
        json.dumps(payload, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )


def legacy_artifact_acceptor(
    *,
    sink: _ArtifactSink,
    mode: str = "loose",
):
    """返回可注入 Executor 的 Acceptor。"""

    if mode not in {"loose", "node-check"}:
        raise ValueError("acceptance 必须是 loose|node-check")

    def accept(task: Task, response: ApiResponse) -> AcceptanceReport:
        checks: list[str] = ["response_ok"]
        errors: list[str] = []
        validator_errors: list[str] = []
        _write_raw_audit(
            sink,
            task,
            response,
            response.parsed_body if isinstance(response.parsed_body, Mapping) else None,
        )

        if response.task_id != task.id:
            errors.append(f"响应 task_id={response.task_id!r} 不匹配")

        # 截断/非法 JSON：先用 ACS 文本抽取捞完整文件，再决定；禁止整包作废已完整文件。
        body_preview = response.parsed_body if isinstance(response.parsed_body, Mapping) else None
        truncated_hint = (getattr(response, "error_type", None) == "output_truncated") or (
            (not response.ok) and _looks_output_truncated(response, body_preview)
        )
        if truncated_hint:
            checks.append("output_truncated_detected")

        if not response.ok and not truncated_hint and body_preview is None:
            errors.append(f"outcome={response.outcome.value}")

        body = response.parsed_body
        checks.append("body_parsed")
        if not isinstance(body, Mapping):
            # ACS 文本抽取 / 截断 JSON 部分恢复
            raw = response.raw_body if isinstance(response.raw_body, str) else ""
            recovered = extract_delivery_map(raw)
            checks.append(f"acs_extract:{recovered.get('method')}")
            for note in recovered.get("extract_log") or []:
                checks.append(f"extract_log:{note}")
            files_recovered = recovered.get("files") or {}
            if files_recovered:
                body = {
                    "ok": True,
                    "delivery": "files",
                    "files": files_recovered,
                    "notes": "acs_text_extract_recovery",
                    "_extract": recovered,
                }
            else:
                if truncated_hint:
                    _write_raw_audit(sink, task, response, None)
                    return AcceptanceReport(
                        task.id,
                        False,
                        tuple(checks),
                        (f"OUTPUT_TRUNCATED: error_type={response.error_type!r} "
                         f"outcome={response.outcome.value} usage={dict(response.usage or {})}",),
                    )
                label = getattr(response, "error_type", None) or "invalid_json"
                errors.append(f"parsed_body 不是对象 ({label})")
                _write_raw_audit(sink, task, response, None)
                return AcceptanceReport(task.id, False, tuple(checks), tuple(errors))

        if body.get("ok") is not True:
            errors.append("ok 不为 true")
        else:
            checks.append("ok_true")

        expected = [x for x in (task.payload.get("owned_files") or []) if isinstance(x, str)]
        expected = [p.replace("\\", "/") for p in expected]
        registered = sink.register_manifest(expected)
        checks.append(f"manifest_registered:{len(registered)}")

        files_map, extract_errors, delivery_mode = _extract_delivery_files(body)
        checks.append(f"delivery_mode:{delivery_mode}")
        errors.extend(extract_errors)

        # 若 JSON 体缺文件或声明截断：再用 ACS 抽取从 raw_body 补齐已闭合文件
        raw = response.raw_body if isinstance(response.raw_body, str) else ""
        if raw and (truncated_hint or extract_errors or True):
            recovered = extract_delivery_map(raw)
            checks.append(f"acs_extract_merge:{recovered.get('method')}")
            for path, content in (recovered.get("files") or {}).items():
                if path not in files_map and isinstance(content, str) and content.strip():
                    files_map[path] = content
                    checks.append(f"acs_recovered:{path}")

        # 截断且捞不到任何完整文件 → 仍标 OUTPUT_TRUNCATED（兼容旧单测与空 body）
        if truncated_hint and not files_map and body.get("ok") is not True:
            _write_raw_audit(sink, task, response, body)
            return AcceptanceReport(
                task.id,
                False,
                tuple(checks),
                (f"OUTPUT_TRUNCATED: error_type={response.error_type!r} "
                 f"outcome={response.outcome.value} usage={dict(response.usage or {})}",),
            )

        if delivery_mode == "manifest":
            # 仅登记清单：不要求本轮写入内容，但必须覆盖 expected
            manifest = body.get("manifest")
            if not isinstance(manifest, (list, tuple)):
                errors.append("delivery=manifest 但 manifest 不是数组")
            else:
                got = [str(x).replace("\\", "/") for x in manifest if isinstance(x, str)]
                for path in expected:
                    checks.append(f"manifest:{path}")
                    if path not in got:
                        errors.append(f"清单缺少文件 {path}")
            if errors:
                return AcceptanceReport(task.id, False, tuple(checks), tuple(errors))
            checks.append("manifest_only_ok")
            # 清单登记本身算通过本步；内容交付留给后续 per-file 任务/响应
            return AcceptanceReport(task.id, True, tuple(checks), ())

        # 本任务 owned_files 必须在本轮交付齐全（Executor 单次调用；多文件靠改图拆分）。
        # delivery=file 只是编码形状；若 task 仍挂多个 owned，同样要求收齐。
        for path in files_map:
            if expected and path not in expected:
                errors.append(f"交付了非本模块文件 {path}")
        for path in expected:
            checks.append(f"file:{path}")
            if path not in files_map:
                errors.append(f"缺少文件 {path}")

        # 先落盘本轮已完整识别的文件（即使仍缺其它 owned）；截断不删除已交付。
        written: list[str] = []
        for path, content in list(files_map.items()):
            if expected and path not in expected:
                continue
            result = sink.deliver_file(path, content)
            checks.append(f"deliver:{path}:{result.get('status')}")
            if result.get("status") != "delivered":
                errors.append(f"交付失败 {path}: {result.get('error')}")
            else:
                written.append(path)
                if result.get("hash"):
                    checks.append(f"hash:{path}:{result['hash'][:23]}")
        checks.append(f"written:{len(written)}")

        # 缺文件：标记 OUTPUT_TRUNCATED（若触顶/截断），保留已写文件
        missing = [p for p in expected if p not in written]
        if missing:
            for path in missing:
                sink.delivery[path] = {
                    "path": path,
                    "status": "OUTPUT_TRUNCATED" if (truncated_hint or _looks_output_truncated(response, body)) else "missing",
                    "hash": None,
                    "bytes": 0,
                    "error": "incomplete_or_absent_after_extract",
                }
                checks.append(f"incomplete:{path}")
            _write_raw_audit(
                sink,
                task,
                response,
                body,
                extra={
                    "raw_body_preview": (response.raw_body or "")[:4000]
                    if isinstance(response.raw_body, str)
                    else None,
                    "written": written,
                    "missing": missing,
                },
            )
            trunc = truncated_hint or _looks_output_truncated(response, body)
            msg_prefix = "OUTPUT_TRUNCATED: " if trunc else ""
            # 非本模块污染等硬错误仍返回；缺文件在截断场景标 OUTPUT_TRUNCATED
            hard = [e for e in errors if not e.startswith("缺少文件")]
            miss_msgs = [f"缺少文件 {p}" for p in missing]
            all_errs = tuple(hard + ([f"{msg_prefix}{'; '.join(miss_msgs)}"] if miss_msgs else []))
            return AcceptanceReport(task.id, False, tuple(checks), all_errs or tuple(errors))

        if errors:
            return AcceptanceReport(task.id, False, tuple(checks), tuple(errors))

        if errors:
            return AcceptanceReport(task.id, False, tuple(checks), tuple(errors))

        _write_raw_audit(sink, task, response, body)

        if mode == "node-check":
            # 只对实际交付的 JS 文件做语法检查；非 JS 跳过。
            check_targets = written if delivery_mode == "file" else list(expected)
            for path in check_targets:
                target = sink.workspace / path
                if not _is_node_checkable(path):
                    checks.append(f"skip_node_check_non_js:{path}")
                    continue
                checks.append(f"node_check:{path}")
                if not target.is_file():
                    errors.append(f"落盘后找不到 {path}")
                    continue
                try:
                    proc = subprocess.run(
                        ["node", "--check", str(target)],
                        capture_output=True,
                        text=True,
                        timeout=60,
                        cwd=str(sink.workspace),
                    )
                except FileNotFoundError as exc:
                    validator_errors.append(
                        f"VALIDATOR_ERROR: node 不可用，无法执行 --check：{exc}"
                    )
                    continue
                except (OSError, subprocess.TimeoutExpired) as exc:
                    validator_errors.append(
                        f"VALIDATOR_ERROR: node --check 无法执行：{exc}"
                    )
                    continue
                if proc.returncode != 0:
                    err = (proc.stderr or proc.stdout or "").strip()[:500]
                    # 防御：若仍因扩展名被 node 拒绝，归为验收器错误而非产品代码失败
                    if "ERR_UNKNOWN_FILE_EXTENSION" in err or "Unknown file extension" in err:
                        validator_errors.append(
                            f"VALIDATOR_ERROR: 对非 JS 文件调用了 node --check：{path}: {err}"
                        )
                    else:
                        errors.append(f"node --check 失败 {path}: {err}")

        if validator_errors:
            # 验收器配置/文件类型/运行时错误 → error 字段，不当产品代码 errors
            return AcceptanceReport(
                task.id,
                False,
                tuple(checks),
                tuple(errors),
                error="; ".join(validator_errors),
            )

        passed = not errors
        return AcceptanceReport(task.id, passed, tuple(checks), tuple(errors))

    return accept


def _prepare_workdir(cfg: LegacyDocConfig) -> tuple[Path, Path]:
    run_dir = cfg.workdir
    run_dir.mkdir(parents=True, exist_ok=True)
    workspace = run_dir / "workspace"
    workspace.mkdir(parents=True, exist_ok=True)
    if cfg.copy_materials:
        # 只读引用：复制 TASK 到 run 根，便于复盘；不碰旧 ACS 目录内容以外的写入
        for src, name in (
            (cfg.task_md_path, "TASK.md"),
            (cfg.task_input_path, "TASK_INPUT.json"),
        ):
            dst = run_dir / name
            if not dst.exists():
                dst.write_bytes(Path(src).read_bytes())
    return run_dir, workspace


def run_legacy_doc(cfg: LegacyDocConfig) -> RunOutcome:
    if not isinstance(cfg.contract_repair_limit, int) or isinstance(cfg.contract_repair_limit, bool) or cfg.contract_repair_limit < 0:
        raise ValueError("contract_repair_limit must be a nonnegative integer")
    task_input = load_task_input(cfg.task_input_path)
    task_md = Path(cfg.task_md_path).read_text(encoding="utf-8")
    tasks = build_legacy_tasks(
        task_input, task_md=task_md, module_ids=cfg.module_ids
    )
    run_dir, workspace = _prepare_workdir(cfg)
    sink = _ArtifactSink(workspace)
    references = task_input.get("reference_files", {})
    owned = {p for task in tasks for p in task.payload.get("owned_files", ())}
    for path, content in references.items():
        target = sink._safe_target(path)
        if target is None or path in owned:
            raise ValueError("reference material path must be safe and disjoint from output ownership")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")

    kind = cfg.client_kind.strip().lower()
    if kind in {"", "fake"}:
        client: SchedulerClient = make_placeholder_client(tasks)
    elif kind in {"http", "real"}:
        kwargs: dict[str, Any] = {
            "timeout_seconds": cfg.timeout_seconds,
            "raw_dir": workspace / "_raw_responses",
        }
        if cfg.model:
            kwargs["model"] = cfg.model
        client = create_client("http", **kwargs)
    elif kind == "native":
        client = create_client("native", bridge_dir=cfg.native_bridge_dir or run_dir / "native-bridge",
                               timeout_seconds=cfg.timeout_seconds)
    else:
        raise ValueError(f"未知 client: {cfg.client_kind!r}")

    # Plan before dispatch; supplied plans also support reproducible offline runs.
    from feasibility_scheduler.adapters.contract_plan import attach_plan, generate_plan

    plan = task_input.get("contract_plan")
    if plan is None and kind in {"http", "real", "native"}:
        plan = generate_plan(client, tasks, task_md)
    if plan is not None:
        from feasibility_scheduler.adapters.contract_checks import requirement_ledger
        if plan.get("version") != 2:
            raise ValueError("runtime contract enforcement requires version 2; migrate textual contracts to executable checks")
        if plan.get("requirements") != requirement_ledger(task_md):
            raise ValueError("contract requirements differ from the original TASK source")
        tasks = attach_plan(tasks, plan)
        (run_dir / "contract.json").write_text(
            json.dumps(plan, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        from feasibility_scheduler.adapters.contract_runtime import composition_task
        tasks.append(composition_task(tasks, plan))
        if isinstance(client, _PlaceholderClient):
            client = make_placeholder_client(tasks)

    store = TaskStore(run_dir / "state.sqlite3")
    log = EventLog(run_dir / "events.jsonl", run_id=run_dir.name)
    acceptor = legacy_artifact_acceptor(sink=sink, mode=cfg.acceptance)
    if plan is not None:
        from feasibility_scheduler.adapters.contract_runtime import ContractAcceptor
        acceptor = ContractAcceptor(acceptor, sink, run_dir, repairable_files=owned,
                                    external_checkers=cfg.external_checkers)

    # 外部门禁：只登记当前启用的适配验收模式（judge_run 要求全部为真）
    external = {
        "LegacyAdapterAcceptanceMode": True,
        f"LegacyAcceptance:{cfg.acceptance}": True,
    }

    policy = (cfg.policy or "rewrite").strip().lower()
    if policy not in {"rewrite", "fixed"}:
        store.close()
        raise ValueError(f"policy 必须是 rewrite|fixed，收到 {cfg.policy!r}")

    # 延迟导入，避免与 rewrite_executor 文档交叉引用时的循环
    from feasibility_scheduler.adapters.rewrite_executor import GraphRewriteExecutor

    try:
        exec_kwargs = dict(
            store=store,
            log=log,
            client=client,
            acceptor=acceptor,
            max_concurrency=cfg.max_concurrency,
            max_attempts=cfg.max_attempts,
            lease_seconds=cfg.lease_seconds,
            external_gates=external,
        )
        if policy == "rewrite":
            executor = GraphRewriteExecutor(tasks, enable_rewrite=True, **exec_kwargs)
        else:
            executor = PromptFromPayloadExecutor(tasks, **exec_kwargs)
        executor.contract_repair_limit = cfg.contract_repair_limit
        outcome = executor.run()
        rewrite_history = list(getattr(executor, "rewrite_history", []))
    finally:
        store.close()

    summary = {
        "ok": outcome.ok,
        "exit_code": outcome.exit_code,
        "verdict": outcome.verdict.to_dict(),
        "states": {k: v.value for k, v in outcome.states.items()},
        "reports": {k: v.to_dict() for k, v in outcome.reports.items()},
        "max_in_flight": outcome.max_in_flight,
        "client_kind": kind,
        "acceptance": cfg.acceptance,
        "policy": policy,
        "module_ids": [t.id for t in tasks],
        "final_task_ids": list(outcome.states.keys()),
        "rewrite_history": rewrite_history,
        "contract_check_results": getattr(acceptor, "results", {}),
        "workdir": str(run_dir),
        "workspace": str(workspace),
        "written_files": list(sink.written),
        "delivery": sink.delivery_snapshot(),
        "limitations": [
            "旧题完整 Node 行为验收（33 ops / CLI / HTTP / 持久化）未接入本适配层；"
            f"当前 acceptance={cfg.acceptance}。",
            "模型须返回 JSON；推荐 manifest/file 逐文件交付；批量 files 仍兼容但易触顶。"
            "触顶截断标 OUTPUT_TRUNCATED；JSON 失败且抽不出文件为 "
            "invalid_format_no_artifact，只允许一次 ACS fence 格式修复。",
            "node-check 仅对 .js/.mjs/.cjs；非 JS 跳过；验收器错误标 VALIDATOR_ERROR。",
            "未修改可行性内核；prompt / 改图决策均在 adapters 层。",
            "policy=rewrite 启用 C 组风格 keep/split/merge 候选比选与原子改图；"
            "policy=fixed 保持初始 DAG（旧瘦适配）。",
        ],
    }
    # 固定 Asia/Shanghai = UTC+8，避免 Windows 缺 tzdata 时 zoneinfo 失败
    shanghai = timezone(timedelta(hours=8), name="Asia/Shanghai")
    summary["finished_at_asia_shanghai"] = datetime.now(shanghai).isoformat(
        timespec="seconds"
    )

    (run_dir / "summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return outcome


